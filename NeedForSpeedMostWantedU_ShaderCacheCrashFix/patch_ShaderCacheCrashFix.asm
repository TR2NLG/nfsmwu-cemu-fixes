; Need for Speed Most Wanted U - Shader Cache Crash Fix (EU, update v32)
;
; Cemu reads a fetch shader (the description of the vertex data of a draw) from the game's
; memory when its graphics thread gets to the draw, with the size the game declared when it
; called GX2SetFetchShader. The game keeps its fetch shaders in buffers that it reuses, among
; them a ring with room for 512 fetch shaders, so the contents can belong to another object by
; then. If the new contents need more instructions than the declared size covers, Cemu stores a
; fetch shader in its shader cache that is cut off, and Cemu 2.6 crashes when it loads that
; entry on the next start ("Compiling shaders", Exception 0x80000003 at Cemu.exe+0x48994e).
;
; This patch replaces all eight calls of GX2SetFetchShader. It works out how many bytes the
; program needs from its own control instructions, keeps one unchanging copy of every distinct
; program in memory of its own, and passes that copy with the correct size to Cemu. Cemu then
; never sees a program that changes under it or a size that is too small. Identical programs
; share one copy, found through a small hash table. If anything looks implausible, or the
; memory for 256 copies is used up, the original call is made unchanged.
;
; The memory is the block of zeros at the end of this file (fsMem). From its first address
; that is a multiple of 256: +0 number of copies, +256 hash table with 1024 entries, +0x1100
; the copies, 256 bytes each, with their length at +252.
;
; Statistics at the start of the code cave (big endian), marker "TR2FSHDR":
; +8 calls, +12 calls where the program needed more than the declared size, +16 copies made,
; +20 calls passed through unchanged, +24 address of the memory, +28 last GX2FetchShader seen
; ---------------------------------------------------------------------------------------------

